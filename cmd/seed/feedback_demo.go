func seedFeedbackDemo(db *gorm.DB) error {
	var count int64
	if err := db.Model(&models.UserFeedback{}).Count(&count).Error; err != nil {
		return err
	}
	target := int64(320)
	if count >= target {
		fmt.Printf("feedback already enough: %d\n", count)
		return nil
	}

	var users []models.User
	if err := db.Where("role = ?", models.UserRoleRailway).
		Where("name <> ''").
		Order("id ASC").
		Limit(1200).
		Find(&users).Error; err != nil {
		return err
	}
	if len(users) == 0 {
		return fmt.Errorf("no railway users for feedback seed")
	}

	rng := rand.New(rand.NewSource(20261107))
	need := int(target - count)
	now := time.Now()
	created := 0
	for i := 0; i < need; i++ {
		u := users[rng.Intn(len(users))]
		tpl := feedbackTemplates[rng.Intn(len(feedbackTemplates))]
		// Spread over ~120 days, weekday-biased daytime hours.
		dayOffset := rng.Intn(120)
		hour := 8 + rng.Intn(12)
		if rng.Float32() < 0.15 {
			hour = 20 + rng.Intn(3)
		}
		minute := rng.Intn(60)
		second := rng.Intn(60)
		when := time.Date(now.Year(), now.Month(), now.Day(), hour, minute, second, 0, time.Local).
			AddDate(0, 0, -dayOffset)

		// Slightly paraphrase by appending concrete context tags.
		sites := []string{
			"格尔木工区", "那曲驻勤点", "西宁车辆段", "拉萨西站", "德令哈折返段",
			"安多作业队", "沱沱河巡养工区", "昆仑山隧道口", "羊八井供电车间", "海西货场",
		}
		site := sites[rng.Intn(len(sites))]
		text := fmt.Sprintf("%s（反映单位：%s；工号关联用户 %d）", tpl.text, site, u.ID)

		phone := u.PhoneNumber
		if phone == "" {
			phone = u.Phone
		}
		fb := models.UserFeedback{
			UserID:        u.ID,
			Name:          u.Name,
			PhoneNumber:   phone,
			FeedbackTitle: tpl.title,
			FeedbackText:  text,
			FeedbackDate:  when,
		}
		if err := db.Create(&fb).Error; err != nil {
			return err
		}
		created++
	}
	fmt.Printf("feedback seeded: +%d (total target >= %d)\n", created, target)
	return nil
}
